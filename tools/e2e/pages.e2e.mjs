/** Fresh state for a flow (a retried flow then behaves like the first run): default settings + mock worker state. */
async function resetState(h, mock) {
  await h.evaluateInExtensionPage(async (isMock) => {
    const all = await chrome.storage.local.get(null);
    await chrome.storage.local.remove(Object.keys(all).filter((k) => k.startsWith('settings.')));
    if (isMock) await chrome.runtime.sendMessage({ __test: 'resetAll' });
  }, !!mock);
}

/** Replaces the text of an input like a user would (select all + type). */
async function retype(page, selector, text, finalKey) {
  await page.$eval(selector, (el) => {
    el.focus();
    el.select();
  });
  await page.keyboard.type(text);
  if (finalKey) await page.keyboard.press(finalKey);
}

/** Every focusable control has an accessible name. Returns a list of offenders. */
const a11yAudit = (page) =>
  page.evaluate(() => {
    const bad = [];
    const named = (el) => {
      if (el.getAttribute('aria-label')) return true;
      const lb = el.getAttribute('aria-labelledby');
      if (lb && lb.split(/\s+/).some((id) => (document.getElementById(id) || {}).textContent)) return true;
      if (el.title) return true;
      if (el.labels && Array.from(el.labels).some((l) => l.textContent.trim())) return true;
      return !!(el.textContent || '').trim();
    };
    for (const el of document.querySelectorAll('button, a[href], select, input, [role="switch"], [role="radiogroup"]')) {
      if (el.closest('[aria-hidden="true"]') || el.type === 'hidden' || el.getAttribute('aria-hidden') === 'true') continue;
      const r = el.getBoundingClientRect();
      const hiddenInput = el.tagName === 'INPUT' && (el.type === 'checkbox' || el.type === 'radio' || el.type === 'file');
      if (!hiddenInput && r.width === 0 && r.height === 0) continue;
      if (!named(el)) bad.push(el.outerHTML.slice(0, 120));
    }
    return bad;
  });

