function watchConsole(page, label, sink) {
  page.on('console', (msg) => {
    const type = msg.type();
    const text = msg.text();
    if (type === 'error' || type === 'assert' || (type === 'warning' && /\[AYT\]/.test(text))) sink.push(`${label}: [${type}] ${text}`);
  });
  page.on('pageerror', (err) => sink.push(`${label}: [pageerror] ${err && err.message}`));
}

