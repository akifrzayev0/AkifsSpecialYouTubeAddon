/** The real worker opens the options page on first install (onInstalled): wait for it and close it, so it cannot
 *  steal the foreground from the pages under test later. Returns its URL (or null). */
async function closeInstallTab(h) {
  const deadline = Date.now() + 10000;
  while (Date.now() < deadline) {
    const pages = await h.browser.pages();
    const opt = pages.find((pg) => pg.url().includes('/options/options.html'));
    if (opt) {
      const url = opt.url();
      await sleep(500); // let it finish loading (it asks the worker for the companion status)
      await opt.close().catch(() => {});
      return url;
    }
    await sleep(250);
  }
  return null;
}

