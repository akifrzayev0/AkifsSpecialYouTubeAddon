function prepareMockExtension() {
  const dest = path.join(OUT, 'ext-mock');
  fs.rmSync(dest, { recursive: true, force: true });
  fs.cpSync(EXT, dest, { recursive: true });
  fs.mkdirSync(path.join(dest, 'background'), { recursive: true });
  fs.writeFileSync(path.join(dest, 'background', 'service-worker.js'), MOCK_SW);
  // Stub content-script files that other modules may not have written yet (Chrome refuses to load otherwise).
  const manifest = JSON.parse(fs.readFileSync(path.join(dest, 'manifest.json'), 'utf8'));
  for (const cs of manifest.content_scripts || []) for (const f of [...(cs.js || []), ...(cs.css || [])]) {
    const p = path.join(dest, f);
    if (!fs.existsSync(p)) fs.writeFileSync(p, '/* e2e stub */\n');
  }
  // Two settings without dedicated controls -> the options page must show them under "Advanced".
  const cPath = path.join(dest, 'shared', 'constants.js');
  const src = fs.readFileSync(cPath, 'utf8');
  const marker = /(\n(\s*)shortsToWatch: false,[^\n]*\n)/;
  let extras = false;
  if (marker.test(src)) {
    fs.writeFileSync(cPath, src.replace(marker, (m, line, indent) => `${line}${indent}e2eExtraFlag: false,\n${indent}e2eExtraLevel: 3,\n`));
    extras = true;
  }
  return { dir: dest, extras };
}

