/** Opens popup.html in a 380x600 tab, faking the active tab (a real popup queries the YouTube tab it was opened on). */
async function openPopup(h, { tab, scheme, sink, label }) {
  const page = await h.browser.newPage();
  watchConsole(page, label, sink);
  await page.setViewport({ width: 380, height: 600, deviceScaleFactor: 1 });
  await page.emulateMediaFeatures([{ name: 'prefers-color-scheme', value: scheme }]);
  await page.evaluateOnNewDocument((fakeTab) => {
    window.__e2e = { sentToTab: [], closed: 0, created: [] };
    window.close = () => {
      window.__e2e.closed++;
    };
    if (window.chrome && chrome.tabs) {
      chrome.tabs.query = async () => (fakeTab ? [fakeTab] : []);
      chrome.tabs.sendMessage = (tabId, msg, cb) => {
        window.__e2e.sentToTab.push({ tabId, msg });
        if (typeof cb === 'function') setTimeout(cb, 0);
      };
      chrome.tabs.create = async (o) => {
        window.__e2e.created.push(o);
        return { id: 1 };
      };
    }
  }, tab);
  await page.goto(`chrome-extension://${h.extensionId}/popup/popup.html`, { waitUntil: 'domcontentloaded' });
  // The real worker opens the options page on first install; a background tab renders no frames and
  // puppeteer clicks (IntersectionObserver) would never finish -> keep the page under test in front.
  await page.bringToFront();
  await page.waitForSelector('#app:not([aria-busy]) .pp-header', { timeout: 15000 });
  return page;
}

