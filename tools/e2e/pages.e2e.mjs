const results = [];
function check(name, cond, detail) {
  results.push({ name, ok: !!cond, detail: detail || '' });
  console.log(`${cond ? 'PASS' : 'FAIL'} ${name}${detail ? ' — ' + detail : ''}`);
}
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

async function retry(label, fn) {
  try {
    return await fn();
  } catch (e) {
    if (/ProtocolError|protocol|Target closed|Session closed|timed out/i.test(String(e && e.message))) {
      console.warn(`! retrying ${label}: ${e.message}`);
      await sleep(1000);
      return fn();
    }
    throw e;
  }
}

